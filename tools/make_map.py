#!/usr/bin/env python3
"""Make the dot-matrix world map used by the "Sydney, working worldwide" section.

Input : a world-atlas TopoJSON land file (Natural Earth 1:110m, public domain), e.g.
        curl -o land-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json
Output: js/map-data.js — the land mask as a bitstring (one bit per dot), drawn on a canvas by js/motion.js.

The map is Pacific-centred (60°E → 30°W) so Sydney and the Americas sit on one sheet.
Run:  python3 tools/make_map.py path/to/land-110m.json
"""
import base64
import json
import pathlib
import sys

LON0, LON1 = 60.0, 330.0          # east longitudes; 330 = 30°W
LAT0, LAT1 = 74.0, -56.0
STEP = 1.6                        # degrees between dots

topo = json.loads(pathlib.Path(sys.argv[1]).read_text())
sx, sy = topo['transform']['scale']
tx, ty = topo['transform']['translate']

arcs = []
for arc in topo['arcs']:                      # delta-decode the quantised arcs
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx
        y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)


def ring(indices):
    out = []
    for i in indices:
        pts = arcs[i] if i >= 0 else arcs[~i][::-1]
        out.extend(pts if not out else pts[1:])
    return out


rings = []
for geom in topo['objects']['land']['geometries']:
    polys = geom['arcs'] if geom['type'] == 'MultiPolygon' else [geom['arcs']]
    for poly in polys:
        for r in poly:
            pts = ring(r)
            xs = [p[0] for p in pts]
            ys = [p[1] for p in pts]
            rings.append((min(xs), max(xs), min(ys), max(ys), pts))


def on_land(lon, lat):
    inside = False                                     # even-odd over every ring handles holes
    for x0, x1, y0, y1, pts in rings:
        if lon < x0 or lon > x1 or lat < y0 or lat > y1:
            continue
        j = len(pts) - 1
        for i in range(len(pts)):
            xi, yi = pts[i]
            xj, yj = pts[j]
            if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
                inside = not inside
            j = i
    return inside


cols = int((LON1 - LON0) / STEP) + 1
rows = int((LAT0 - LAT1) / STEP) + 1
bits = []
for r in range(rows):
    lat = LAT0 - r * STEP
    for c in range(cols):
        lon = LON0 + c * STEP
        lon = lon - 360 if lon >= 180 else lon
        bits.append(1 if on_land(lon, lat) else 0)

packed = bytearray()
for i in range(0, len(bits), 8):
    byte = 0
    for b in bits[i:i + 8]:
        byte = byte << 1 | b
    packed.append(byte << (8 - len(bits[i:i + 8])))

out = pathlib.Path(__file__).resolve().parent.parent / 'js' / 'map-data.js'
out.write_text(
    '/* Generated by tools/make_map.py from Natural Earth 1:110m land (public domain). */\n'
    f'window.IP_MAP = {json.dumps({"lon0": LON0, "lon1": LON1, "lat0": LAT0, "lat1": LAT1, "step": STEP, "cols": cols, "rows": rows, "bits": base64.b64encode(bytes(packed)).decode()})};\n'
)
print(f'{cols}x{rows} grid, {sum(bits)} land dots → {out}')
